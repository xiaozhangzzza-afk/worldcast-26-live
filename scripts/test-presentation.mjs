import assert from 'node:assert/strict';
await import('../assets/js/analytics.js');
await import('../assets/js/presentation.js');
const now=Date.parse('2026-10-09T01:00:00Z'),iso=n=>new Date(n).toISOString();
const match={id:'test',competitionId:'eng.1',date:iso(now+3600000),homeScore:null,awayScore:null,completed:false,live:false};
const store={freshness:{'eng.1':{mode:'live',lastSuccessAt:iso(now),sourceUpdatedAt:iso(now)}}};
assert.equal(FM_PRESENTATION.status(match,store,now).phase,'upcoming');
assert.equal(FM_PRESENTATION.status({...match,date:iso(now-1)},store,now).phase,'awaiting');
assert.equal(FM_PRESENTATION.status({...match,completed:true},store,now).phase,'completed');
let live={...match,live:true,displayClock:'72′',clockSeconds:4320,dataCheckedAt:iso(now)};
assert.equal(FM_PRESENTATION.status(live,store,now).sourceUpdatedAt,null,'Do not borrow another event or feed timestamp');
assert.equal(FM_PRESENTATION.status(live,store,now+40000).clock,'72′','No simulated match-clock progression');
assert.equal(FM_PRESENTATION.status({...live,sourceUpdatedAt:iso(now-180000)},store,now).sourceState,'stale');
assert.equal(FM_PRESENTATION.status(live,store,now+65000).sourceState,'stale');
assert.equal(FM_PRESENTATION.status({...live,snapshotRecordedAt:iso(now-3600000)},store,now).sourceState,'snapshot');
assert.equal(FM_PRESENTATION.status(live,{isSnapshot:true,freshness:{'eng.1':{mode:'snapshot',checkedAt:iso(now-1000)}}},now).sourceState,'fresh','Successful newer detail check overrides an older failed competition check');
assert.equal(FM_PRESENTATION.status({...match,competitionId:'fifa.world'},store,now).sourceState,'archive');
assert.equal(FM_PRESENTATION.model({...match,predictedScore:'1–0',predictionSource:'local-poisson'},null).kind,'local');
assert.equal(FM_PRESENTATION.model({...match,completed:true,predictedScore:'1–0'},null).kind,'missing','Finished game requires a frozen record');
assert.equal(FM_PRESENTATION.model({...match,completed:true},{predictedScore:'1–0',modelVersion:'local-poisson-v1'}).frozen,true);
assert.equal(FM_PRESENTATION.changes([live],[{...live,dataCheckedAt:iso(now+20000),clockSnapshotAt:iso(now+20000)}]),0);
assert.equal(FM_PRESENTATION.changes([live],[{...live,displayClock:'73′'}]),1);
assert.equal(FM_PRESENTATION.changes([live],[{...live,homeScore:1}]),1);
assert.equal(FM_PRESENTATION.changes([live],[{...live,timeline:[{id:'goal',type:'goal',minute:'73′',player:'Test'}]}]),1);
console.log('PASS source/request separation, no simulated clocks, snapshot/stale badges, no retrospective predictions, factual sync feedback');
